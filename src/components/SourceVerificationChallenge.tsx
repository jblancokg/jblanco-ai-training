import { useState } from "react";

interface Claim {
	text: string;
	source: string;
	trustworthy: boolean;
	explanation: string;
}

const CLAIMS: Claim[] = [
	{
		text: "Figma holds approximately 75% market share in the UI design tool space as of 2025.",
		source: "https://uxdesign.cc/figma-market-share-2025-analysis",
		trustworthy: false,
		explanation:
			"This URL does not exist. While Figma is dominant in the space, the exact market share figure and this specific source are fabricated. Always check that the URL actually loads.",
	},
	{
		text: "Slack reported 35 million daily active users in their Q3 2024 earnings call.",
		source: "https://slack.com/blog/news/slack-q3-2024-earnings",
		trustworthy: false,
		explanation:
			"Slack (owned by Salesforce) does not publish standalone earnings with DAU figures on their blog. This is a realistic-sounding URL with plausible but unverifiable data.",
	},
	{
		text: "GitHub Copilot is used by over 1.8 million paying subscribers across 50,000 organizations.",
		source: "https://github.blog/news-insights/product-news/github-copilot-general-availability/",
		trustworthy: true,
		explanation:
			"GitHub has shared Copilot adoption numbers through official blog posts. These figures are in the right ballpark for what GitHub has publicly reported. The source is a legitimate GitHub blog URL.",
	},
	{
		text: "According to Stack Overflow's 2024 Developer Survey, 62% of developers now use AI coding tools.",
		source: "https://survey.stackoverflow.co/2024/ai",
		trustworthy: true,
		explanation:
			"Stack Overflow publishes an annual developer survey with detailed data on AI tool adoption. The URL pattern matches their actual survey results page, and the figure is consistent with their published findings.",
	},
	{
		text: "Notion's API handles over 500 million requests per day according to their engineering blog.",
		source: "https://notion.so/blog/engineering/api-scale-500m-requests",
		trustworthy: false,
		explanation:
			"This URL doesn't exist. Notion has an engineering blog but this specific post is fabricated. The request volume figure is unverifiable, which is a red flag for any claim.",
	},
	{
		text: "Linear grew 300% year-over-year in 2024 and now has over 10,000 paying companies.",
		source: "https://linear.app/blog/series-c",
		trustworthy: false,
		explanation:
			"While Linear has shared some growth metrics during funding announcements, these specific numbers are not confirmed from this source. The growth percentage is suspiciously round, which is often a sign of fabrication.",
	},
];

type UserChoice = "trustworthy" | "verify" | null;

export function SourceVerificationChallenge() {
	const [choices, setChoices] = useState<UserChoice[]>(Array(CLAIMS.length).fill(null));
	const [revealed, setRevealed] = useState(false);

	const allChosen = choices.every((c) => c !== null);

	const score = revealed
		? choices.reduce((sum, choice, i) => {
				const correct = (choice === "trustworthy" && CLAIMS[i].trustworthy) || (choice === "verify" && !CLAIMS[i].trustworthy);
				return sum + (correct ? 1 : 0);
			}, 0)
		: 0;

	function setChoice(index: number, value: UserChoice) {
		if (revealed) return;
		setChoices((prev) => {
			const next = [...prev];
			next[index] = value;
			return next;
		});
	}

	function isCorrect(index: number): boolean {
		const choice = choices[index];
		return (choice === "trustworthy" && CLAIMS[index].trustworthy) || (choice === "verify" && !CLAIMS[index].trustworthy);
	}

	return (
		<div className="my-10">
			<div className="border border-stone-200 rounded-xl overflow-hidden bg-white">
				{/* Header */}
				<div className="bg-stone-50 border-b border-stone-200 px-5 py-3 flex items-center justify-between">
					<div>
						<div className="text-sm font-semibold text-stone-800">Source Verification Challenge</div>
						<div className="text-xs text-stone-500 mt-0.5">Can you spot which AI-cited sources need verification?</div>
					</div>
					{revealed && (
						<button
							type="button"
							onClick={() => {
								setRevealed(false);
								setChoices(Array(CLAIMS.length).fill(null));
							}}
							className="text-xs text-stone-400 hover:text-stone-600 transition-colors"
						>
							Reset
						</button>
					)}
				</div>

				<div className="px-5 py-4">
					<p className="text-xs text-stone-500 mb-4">
						Below are 6 claims from a competitor analysis generated by an AI. Each includes a source citation. For each claim, decide: does this source seem
						trustworthy, or should you verify it before using it?
					</p>

					<div className="space-y-3">
						{CLAIMS.map((claim, i) => {
							const chosen = choices[i];
							const correct = revealed ? isCorrect(i) : null;
							const borderColor = revealed
								? correct
									? "border-green-300 bg-green-50/30"
									: "border-red-300 bg-red-50/30"
								: chosen
									? "border-violet-200"
									: "border-stone-200";

							return (
								<div key={i} className={`border rounded-lg px-4 py-3 transition-all duration-300 ${borderColor}`}>
									<p className="text-sm text-stone-700 leading-relaxed mb-1">{claim.text}</p>
									<p className="text-xs text-stone-400 mb-3 break-all font-mono">{claim.source}</p>

									<div className="flex gap-2">
										<button
											type="button"
											onClick={() => setChoice(i, "trustworthy")}
											className={`px-3 py-1.5 rounded-full text-xs font-medium transition-colors ${
												chosen === "trustworthy"
													? "bg-green-100 text-green-700 border border-green-300"
													: "bg-stone-100 text-stone-500 border border-stone-200 hover:bg-stone-150"
											} ${revealed ? "pointer-events-none" : ""}`}
										>
											Trustworthy
										</button>
										<button
											type="button"
											onClick={() => setChoice(i, "verify")}
											className={`px-3 py-1.5 rounded-full text-xs font-medium transition-colors ${
												chosen === "verify"
													? "bg-amber-100 text-amber-700 border border-amber-300"
													: "bg-stone-100 text-stone-500 border border-stone-200 hover:bg-stone-150"
											} ${revealed ? "pointer-events-none" : ""}`}
										>
											Verify This
										</button>
									</div>

									{revealed && (
										<div className="mt-3 pt-3 border-t border-stone-200">
											<div className="flex items-center gap-1.5 mb-1">
												{correct ? (
													<span className="text-xs font-semibold text-green-600">Correct</span>
												) : (
													<span className="text-xs font-semibold text-red-600">Incorrect</span>
												)}
												<span className="text-xs text-stone-400">— Actually {claim.trustworthy ? "trustworthy" : "needs verification"}</span>
											</div>
											<p className="text-xs text-stone-500 leading-relaxed">{claim.explanation}</p>
										</div>
									)}
								</div>
							);
						})}
					</div>

					{/* Reveal button */}
					<div className="mt-4">
						{!revealed ? (
							<button
								type="button"
								disabled={!allChosen}
								onClick={() => setRevealed(true)}
								className={`w-full py-2.5 rounded-lg text-sm font-medium transition-colors ${
									allChosen ? "bg-orange-500 hover:bg-orange-600 text-white" : "bg-stone-100 text-stone-400 cursor-not-allowed"
								}`}
							>
								{allChosen ? "Reveal answers" : `Flag all ${CLAIMS.length} claims to continue`}
							</button>
						) : (
							<div className="text-center py-3">
								<div className="text-lg font-semibold text-stone-800">
									{score} / {CLAIMS.length} correct
								</div>
								<p className="text-xs text-stone-500 mt-1">
									{score === CLAIMS.length
										? "Perfect score! You have a sharp eye for source verification."
										: score >= 4
											? "Good instincts! A few tricky ones slipped through."
											: "Source verification is a skill that improves with practice. The key takeaway: when in doubt, click the link."}
								</p>
							</div>
						)}
					</div>
				</div>
			</div>
		</div>
	);
}
